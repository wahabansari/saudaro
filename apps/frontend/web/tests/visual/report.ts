import fs from 'node:fs';
import path from 'node:path';
import { components, readJson } from './helpers';

type Px = { status: 'PASS' | 'DIFF' | 'MISSING' | 'N/A'; pct?: number; px?: number; preview?: number[]; gallery?: number[] };
type Row = { impact: string; rule: string; selector: string; wrapper: string | null };
type A11y = {
  axe: Record<string, Row[]>;
  reflow: Record<string, { ok: boolean; scrollWidth: number; clientWidth: number; offenders: string[] }>;
  navy: { forms?: { before: string; after: string; ok: boolean } };
};

const CAUSES_FILE = path.join(__dirname, 'causes.json'); // hand-written probable causes, by component
const fmt = (r?: Px) => (!r ? 'n/a' : r.status === 'N/A' ? 'N/A' : r.status === 'MISSING' ? 'MISSING' : r.status === 'PASS' ? '0' : `${r.pct!.toFixed(2)}% (${r.px} px)`);
const sizeNote = (r?: Px) => (r?.status === 'DIFF' && r.preview!.join() !== r.gallery!.join() ? `size ${r.preview!.join('x')} vs ${r.gallery!.join('x')}` : '');

function pixelSection() {
  const [d, m] = [readJson<Record<string, Px>>('pixel-1440.json') ?? {}, readJson<Record<string, Px>>('pixel-375.json') ?? {}];
  const causes: Record<string, string> = fs.existsSync(CAUSES_FILE) ? JSON.parse(fs.readFileSync(CAUSES_FILE, 'utf8')) : {};
  const rows = components.map((name) => {
    const [a, b] = [d[name], m[name]];
    const status = a?.status === 'N/A' ? 'N/A' : [a, b].some((r) => r?.status === 'MISSING') ? 'MISSING' : [a, b].every((r) => r?.status === 'PASS') ? 'PASS' : 'DIFF';
    const severity = status === 'DIFF' ? Math.max(a?.pct ?? 0, b?.pct ?? 0) : -1;
    const note = [causes[name], sizeNote(a) && `1440 ${sizeNote(a)}`, sizeNote(b) && `375 ${sizeNote(b)}`].filter(Boolean).join('; ');
    return { name, a, b, status, severity, note };
  });
  const order = { DIFF: 0, MISSING: 1, PASS: 2, 'N/A': 3 };
  rows.sort((x, y) => order[x.status] - order[y.status] || y.severity - x.severity || x.name.localeCompare(y.name));
  const count = (s: string) => rows.filter((r) => r.status === s).length;
  return [
    `Threshold 0.1 (pixelmatch). Mismatch is a share of the larger of the two screenshots; size differences count as mismatched pixels.`,
    `PASS ${count('PASS')} / DIFF ${count('DIFF')} / MISSING ${count('MISSING')} / N/A ${count('N/A')} (overlays that open from a trigger, tested by keyboard) of ${rows.length}. DIFF sorted by worst-viewport mismatch.`,
    `Images: \`apps/frontend/web/tests/visual/.output/diff/<width>/<Name>.{preview,gallery,diff}.png\` (git-ignored).`,
    '',
    '| Component | 1440 mismatch | 375 mismatch | Status | Probable cause |',
    '|---|---|---|---|---|',
    ...rows.map((r) => `| ${r.name} | ${fmt(r.a)} | ${fmt(r.b)} | ${r.status === 'PASS' ? 'PASS (0 px)' : r.status} | ${r.note} |`),
  ];
}

const IMPACT = ['critical', 'serious', 'moderate', 'minor'];
const cell = (s: string) => s.replaceAll('|', '\\|');
function group(rows: Row[]) {
  const map = new Map<string, Row[]>();
  for (const r of rows) {
    const key = [r.impact, r.rule, r.wrapper].join('|');
    map.set(key, [...(map.get(key) ?? []), r]);
  }
  return [...map.values()]
    .sort((x, y) => IMPACT.indexOf(x[0].impact) - IMPACT.indexOf(y[0].impact) || y.length - x.length)
    .map((g) => `| ${g[0].impact} | ${g[0].rule} | ${g[0].wrapper ?? 'outside wrappers'} | ${g.length} | \`${cell(g[0].selector)}\` |`);
}


function a11ySection() {
  const a = readJson<A11y>('a11y.json');
  const k = readJson<{ results: Record<string, string> }>('keyboard.json')?.results ?? {};
  if (!a) return ['No accessibility results (test did not run).'];
  const out: string[] = [];
  for (const [w, rows] of Object.entries(a.axe ?? {})) {
    const by: Record<string, number> = {};
    rows.forEach((r) => (by[r.impact] = (by[r.impact] ?? 0) + 1));
    out.push(`### axe-core at ${w}px (wcag2a, wcag2aa, wcag21a, wcag21aa, wcag22aa)`, '', `Nodes by impact: ${JSON.stringify(by)}`, '');
    if (rows.length) out.push('Grouped by impact, rule and wrapper; every node is in `.output/a11y.json`.', '', '| Impact | Rule | Component wrapper | Nodes | Example selector |', '|---|---|---|---|---|', ...group(rows), '');
  }
  out.push('### Reflow', '');
  for (const [label, r] of Object.entries(a.reflow ?? {})) out.push(`- ${label}: ${r.ok ? 'PASS' : 'FAIL'} (scrollWidth ${r.scrollWidth}, clientWidth ${r.clientWidth})${r.offenders.length ? `; overflowing: ${r.offenders.join(', ')}` : ''}`);
  out.push('', '### Theme', '', a.navy?.forms ? `- data-theme="navy" on #forms: ${a.navy.forms.ok ? 'PASS' : 'FAIL'} (--ground ${a.navy.forms.before} -> ${a.navy.forms.after})` : '- not run');
  out.push('', '### Keyboard walk-through', '');
  for (const n of ['Dialog', 'Menu', 'Select', 'Tabs', 'Accordion']) out.push(`- ${n}: ${k[n] ?? 'FAIL (see Playwright output)'}`);
  return out;
}

export default function globalTeardown() {
  const md = ['# Visual diff report', '', 'Generated by `npm run test:visual -w @saudaro/web`. Do not edit by hand.', '', '## Pixel check', '', ...pixelSection(), '', '## Accessibility', '', ...a11ySection(), ''];
  fs.writeFileSync(path.resolve(__dirname, '../../../../../docs/visual-diff.md'), md.join('\n'));
}
