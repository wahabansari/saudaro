import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import pg from 'pg';
import { bootstrapServiceRoles, runServiceMigrations } from '@saudaro/database-utils';
import { createTestDatabase, startPostgres, type TestDatabase } from '@saudaro/testing-utils';
import { DB_SERVICES, ROOT, migrationsFolder } from './services.ts';

const PRIVILEGES = ['SELECT', 'INSERT', 'UPDATE', 'DELETE', 'TRUNCATE', 'REFERENCES', 'TRIGGER'];

/** Throwaway passwords for the scratch database that is only introspected. */
const pw = (name: string, kind: 'app' | 'migrator') => `${name}-${kind}-scratch`;

/** Bootstraps every service's roles and applies every service's migrations, like db:bootstrap + db:migrate. */
export async function provision(db: TestDatabase): Promise<void> {
  const admin = new pg.Client({ connectionString: db.adminUrl });
  await admin.connect();
  try {
    await bootstrapServiceRoles(
      admin,
      db.name,
      DB_SERVICES.map((s) => ({
        name: s.name,
        schema: s.schema,
        appPassword: pw(s.name, 'app'),
        migratorPassword: pw(s.name, 'migrator'),
      })),
    );
  } finally {
    await admin.end();
  }
  for (const s of DB_SERVICES) {
    await runServiceMigrations({
      connectionString: db.urlFor(`${s.name}_migrator`, pw(s.name, 'migrator')),
      schema: s.schema,
      migrationsFolder: migrationsFolder(s),
    });
  }
}

const cell = (v: unknown): string =>
  String(v ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\s*\n\s*/g, ' ');

const table = (headers: string[], rows: unknown[][]): string[] => [
  `| ${headers.join(' | ')} |`,
  `|${headers.map(() => '---').join('|')}|`,
  ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`),
  '',
];

type Row = Record<string, string | boolean | null>;

/** Introspects every DB_SERVICES schema as a superuser and renders deterministic Markdown. */
export async function renderDataDictionary(client: pg.Client): Promise<string> {
  const q = async (sql: string, params: unknown[]): Promise<Row[]> => (await client.query(sql, params)).rows;
  const out: string[] = [
    '# Data dictionary',
    '',
    'GENERATED by npm run docs:data-dictionary from the real migrations — do not edit by hand',
    '',
  ];
  for (const s of [...DB_SERVICES].sort((a, b) => a.schema.localeCompare(b.schema))) {
    const files = readdirSync(join(ROOT, s.dir, 'migrations'))
      .filter((f) => f.endsWith('.sql'))
      .sort();
    out.push(
      `## Schema \`${s.schema}\``,
      '',
      `Owning service: \`${s.name}-service\`. Roles: \`${s.name}_svc\` (runtime), \`${s.name}_migrator\` (migrations).`,
      '',
      `Migrations applied: ${files.map((f) => `\`${f}\``).join(', ')}`,
      '',
    );
    const tables = await q(
      `SELECT c.oid::int AS oid, c.relname, c.relrowsecurity, c.relforcerowsecurity, obj_description(c.oid, 'pg_class') AS comment
         FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = $1 AND c.relkind IN ('r', 'p') AND c.relname <> '__migrations' ORDER BY c.relname`,
      [s.schema],
    );
    for (const t of tables) {
      const name = `${s.schema}.${t.relname}`;
      const rel = [t.oid];
      out.push(`### ${name}`, '');
      if (t.comment) out.push(String(t.comment), '');

      const cols = await q(
        `SELECT a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type, NOT a.attnotnull AS nullable,
                pg_get_expr(d.adbin, d.adrelid) AS "default", col_description(a.attrelid, a.attnum) AS comment
           FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
          WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum`,
        rel,
      );
      const described = cols.some((c) => c.comment);
      out.push(
        ...table(
          ['Column', 'Type', 'Nullable', 'Default', ...(described ? ['Description'] : [])],
          cols.map((c) => [
            c.name,
            c.type,
            c.nullable ? 'yes' : 'no',
            c.default,
            ...(described ? [c.comment] : []),
          ]),
        ),
      );

      const cons = await q(
        `SELECT conname AS name, contype AS kind, pg_get_constraintdef(oid) AS def FROM pg_constraint
          WHERE conrelid = $1 AND contype IN ('p', 'u', 'f', 'c') ORDER BY contype, conname`,
        rel,
      );
      const kinds = { p: 'Primary key', u: 'Unique', f: 'Foreign key', c: 'Check' } as const;
      out.push(
        '**Constraints**',
        '',
        ...table(
          ['Name', 'Kind', 'Definition'],
          cons.map((c) => [c.name, kinds[c.kind as keyof typeof kinds], c.def]),
        ),
      );

      const idx = await q(
        `SELECT c.relname AS name, i.indisunique AS "unique", pg_get_indexdef(i.indexrelid) AS def
           FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid WHERE i.indrelid = $1 ORDER BY c.relname`,
        rel,
      );
      out.push(
        '**Indexes**',
        '',
        ...table(
          ['Name', 'Unique', 'Definition (columns, partial predicate)'],
          idx.map((i) => [i.name, i.unique ? 'yes' : 'no', i.def]),
        ),
      );

      const trg = await q(
        `SELECT tgname AS name, pg_get_triggerdef(oid) AS def FROM pg_trigger
          WHERE tgrelid = $1 AND NOT tgisinternal ORDER BY tgname`,
        rel,
      );
      if (trg.length) {
        out.push(
          '**Triggers**',
          '',
          ...table(
            ['Name', 'Definition'],
            trg.map((r) => [r.name, r.def]),
          ),
        );
      }

      out.push(
        `**Row-level security:** enabled: ${t.relrowsecurity ? 'yes' : 'no'}; FORCE: ${t.relforcerowsecurity ? 'yes' : 'no'}`,
        '',
      );
      const pol = await q(
        `SELECT policyname AS name, cmd, roles::text[] AS roles, qual, with_check FROM pg_policies
          WHERE schemaname = $1 AND tablename = $2 ORDER BY policyname`,
        [s.schema, t.relname],
      );
      if (pol.length) {
        out.push(
          ...table(
            ['Policy', 'Command', 'Roles', 'USING', 'WITH CHECK'],
            pol.map((p) => [
              p.name,
              p.cmd,
              (p.roles as unknown as string[]).join(', '),
              p.qual,
              p.with_check,
            ]),
          ),
        );
      }

      const granted = await q(
        `SELECT p AS priv FROM unnest($3::text[]) p WHERE has_table_privilege($1, $2::oid, p) ORDER BY p`,
        [`${s.name}_svc`, t.oid, PRIVILEGES],
      );
      out.push(`**Privileges of \`${s.name}_svc\`:** ${granted.map((g) => g.priv).join(', ') || 'none'}`, '');
    }
  }
  return `${out.join('\n').trimEnd()}\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const server = await startPostgres();
  try {
    const db = await createTestDatabase(server.adminUrl);
    await provision(db);
    const client = new pg.Client({ connectionString: db.adminUrl });
    await client.connect();
    try {
      writeFileSync(join(ROOT, 'docs', 'DATA_DICTIONARY.md'), await renderDataDictionary(client));
    } finally {
      await client.end();
    }
  } finally {
    await server.stop();
  }
}
